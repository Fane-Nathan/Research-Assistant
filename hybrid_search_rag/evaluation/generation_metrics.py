"""
Metrics for evaluating the generation quality of a RAG system.

This module provides functions to assess aspects like faithfulness of the
generated answer to the provided context, and relevance of the answer
to the original query, primarily using an LLM-as-a-judge approach.
"""

import logging
from typing import Dict, Any, Optional

from ..llm_services.llm_interface import LLMInterface

logger = logging.getLogger(__name__)

FAITHFULNESS_RATINGS = {
    "fully supported": 3.0,
    "partially supported": 2.0,
    "not supported": 1.0,
}

class GenerationEvaluationMetrics:
    """
    Encapsulates methods for evaluating generated text from a RAG system.
    """

    def __init__(self, llm_interface: LLMInterface):
        """
        Initializes the GenerationEvaluationMetrics with an LLMInterface instance.

        Args:
            llm_interface: An instance of LLMInterface to be used for LLM-as-judge evaluations.
        """
        if not isinstance(llm_interface, LLMInterface):
            raise TypeError("llm_interface must be an instance of LLMInterface.")
        self.llm_interface = llm_interface

    def assess_faithfulness(
        self,
        generated_answer: str,
        context: str,
        query: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Assesses the faithfulness of the generated answer to the provided context using an LLM.

        The LLM is prompted to determine if the answer is fully supported, partially supported,
        or not supported by the given context.

        Args:
            generated_answer: The answer generated by the RAG system.
            context: The context provided to the RAG system for generating the answer.
            query: The original query (optional, for more context to the judge LLM).

        Returns:
            A dictionary containing:
                - 'rating_str': The string rating from the LLM (e.g., "fully supported").
                - 'score': A numerical score corresponding to the rating.
                - 'explanation': (Optional) Any explanation provided by the LLM.
                - 'error': (Optional) Error message if assessment failed.
        """
        if not generated_answer or not context:
            logger.warning("Faithfulness assessment requires non-empty generated_answer and context.")
            return {"rating_str": "N/A", "score": 0.0, "error": "Missing generated answer or context."}

        query_context_str = f"Original Query (for context): {query}\\n\\n" if query else ""
        prompt = f"""\
Review the following statement and the supporting context carefully.
{query_context_str}Supporting Context:
---
{context}
---

Statement:
---
{generated_answer}
---

Based *only* on the provided Supporting Context, is the Statement fully supported, partially supported, or not supported by the context?
Please respond with one of the following phrases only:
- "Fully supported"
- "Partially supported"
- "Not supported"
"""
        try:
            logger.debug(f"Faithfulness assessment prompt:\\n{prompt}")
            response_text = self.llm_interface.get_llm_response_unary(prompt)
            
            if response_text:
                response_text_lower = response_text.strip().lower()
                # More robust matching
                matched_rating = None
                for rating_key in FAITHFULNESS_RATINGS:
                    if rating_key in response_text_lower:
                        matched_rating = rating_key
                        break
                
                if matched_rating:
                    return {
                        "rating_str": matched_rating,
                        "score": FAITHFULNESS_RATINGS[matched_rating],
                    }
                else:
                    logger.warning(f"Faithfulness LLM response ('{response_text}') not in expected format.")
                    return {"rating_str": response_text, "score": 0.0, "error": "Unrecognized LLM response format."}
            else:
                logger.error("Faithfulness LLM call returned empty response.")
                return {"rating_str": "N/A", "score": 0.0, "error": "LLM returned empty response."}

        except Exception as e:
            logger.error(f"Error during faithfulness assessment LLM call: {e}", exc_info=True)
            return {"rating_str": "N/A", "score": 0.0, "error": str(e)}

    def assess_answer_relevance(
        self,
        query: str,
        generated_answer: str
    ) -> Dict[str, Any]:
        """
        Assesses the relevance of the generated answer to the original query using an LLM.

        The LLM is prompted to rate the relevance on a scale of 1 to 5.

        Args:
            query: The original query posed to the RAG system.
            generated_answer: The answer generated by the RAG system.

        Returns:
            A dictionary containing:
                - 'rating_str': The string rating from the LLM (e.g., "4").
                - 'score': A numerical score (float).
                - 'explanation': (Optional) Any explanation provided by the LLM.
                - 'error': (Optional) Error message if assessment failed.
        """
        if not query or not generated_answer:
            logger.warning("Answer relevance assessment requires non-empty query and generated_answer.")
            return {"rating_str": "N/A", "score": 0.0, "error": "Missing query or generated answer."}

        prompt = f"""\
Review the following Query and the Answer generated in response to it.

Query:
---
{query}
---

Answer:
---
{generated_answer}
---

How relevant is the Answer to the Query? Please rate on a scale of 1 to 5, where:
1 = Not at all relevant
2 = Slightly relevant
3 = Moderately relevant
4 = Relevant
5 = Highly relevant

Provide only the numerical rating (1-5).
"""
        try:
            logger.debug(f"Answer relevance assessment prompt:\\n{prompt}")
            response_text = self.llm_interface.get_llm_response_unary(prompt)

            if response_text:
                response_text_clean = response_text.strip()
                try:
                    score = float([s for s in response_text_clean if s.isdigit()][0])
                    if 1.0 <= score <= 5.0:
                        return {"rating_str": response_text_clean, "score": score}
                    else:
                        logger.warning(f"Answer relevance LLM response ('{response_text_clean}') out of 1-5 range.")
                        return {"rating_str": response_text_clean, "score": 0.0, "error": "LLM response out of range."}
                except (ValueError, IndexError):
                    logger.warning(f"Answer relevance LLM response ('{response_text_clean}') not a valid number.")
                    return {"rating_str": response_text_clean, "score": 0.0, "error": "LLM response not a number."}
            else:
                logger.error("Answer relevance LLM call returned empty response.")
                return {"rating_str": "N/A", "score": 0.0, "error": "LLM returned empty response."}

        except Exception as e:
            logger.error(f"Error during answer relevance assessment LLM call: {e}", exc_info=True)
            return {"rating_str": "N/A", "score": 0.0, "error": str(e)}

if __name__ == '__main__':
    print("Running generation_metrics.py example...")
    try:
        # Initialize the LLMInterface with the new class-based approach
        from ..llm_services.llm_interface import LLMInterface
        
        llm_interface_instance = LLMInterface()
        eval_metrics = GenerationEvaluationMetrics(llm_interface_instance)

        faith_result = eval_metrics.assess_faithfulness(
            generated_answer="The sky is blue due to Rayleigh scattering.",
            context="Sunlight reaches Earth's atmosphere and is scattered in all directions by all the gases and particles in the air. Blue light is scattered more than other colors because it travels as shorter, smaller waves. This is why we see a blue sky most of the time. This phenomenon is called Rayleigh scattering."
        )
        print(f"Faithfulness Assessment: {faith_result}")

        relevance_result = eval_metrics.assess_answer_relevance(
            query="Why is the sky blue?",
            generated_answer="The sky appears blue because of a phenomenon called Rayleigh scattering, where blue light from the sun is scattered more effectively by the Earth's atmosphere than other colors."
        )
        print(f"Answer Relevance Assessment: {relevance_result}")

    except ImportError as ie:
        print(f"Could not run example due to ImportError: {ie}. This might be due to relative imports.")
    except Exception as e:
        print(f"An error occurred during example run: {e}")

